# 2026-11-20: train the MCU-sized low-frequency forest (host/ad3_bridge/lowfreq_forest.py) on all
# labelled runs and write ml/lowfreq_forest/lowfreq_forest_v1.json + .h. Analysis/display only:
# the detector, B2, candidates and the XIAO are unchanged. Features come from the host module so
# training and the review page compute them identically.
#   python train_forest.py            report (leave-one-day-out / leave-one-run-out) and write
#   python train_forest.py --report   report only
import json
import sys
import numpy as np
from common import OUT, WORK, runs, labels
from review import actuation_spans
import lowfreq_activity as lf
import lowfreq_forest as lff
from a9 import Forest, evaluate, ap  # numpy CART / forest and the a8-style measures

KW = dict(n_trees=20, max_depth=5, min_leaf=30, mtry='sqrt', seed=20261120)
NOISE_W = 3.0


def run_data(r):
    run = r['run']
    manifest = json.loads((OUT / run / 'manifest.json').read_text(encoding='utf-8'))
    arm = [(s['t0_s'], s['t1_s']) for s in actuation_spans(OUT / run, manifest)]
    rows = lf.cached_rows(OUT / run / 'samples.f64', WORK.parent / 'review_cache/lowfreq')
    t, X, usable = lff.features(rows, arm)
    base = lf.judge(rows, arm)
    labs, _ = labels(run)
    y = np.zeros(len(t), int); noise = np.zeros(len(t), bool)
    for x in labs:
        a, b = (x['a'] - .5, x['b'] + .5) if x['kind'] == 'NOISE_POINT' else (x['a'], x['b'])
        m = (t + .125 >= a) & (t - .125 <= b)
        if x['kind'] in ('LARVA', 'DIG'): y[m] = 1
        elif x['kind'].startswith('NOISE'): noise |= m
    bon = np.zeros(len(t))
    for s in base['activity_like_spans']:
        bon[(t >= s['t0_s']) & (t <= s['t1_s'])] = 1
    return dict(run=run, day=r['started_at_pc'][:10], t=t, X=X, y=y, noise=noise, keep=usable, base=bon,
                larva=[(x['a'], x['b']) for x in labs if x['kind'] in ('LARVA', 'DIG')],
                nz=[(x['a'], x['b']) for x in labs if x['kind'] == 'NOISE'] + [(x['a'] - .5, x['b'] + .5) for x in labs if x['kind'] == 'NOISE_POINT'])


def xyw(D):
    X = np.concatenate([d['X'][d['keep']] for d in D]); y = np.concatenate([d['y'][d['keep']] for d in D])
    nz = np.concatenate([d['noise'][d['keep']] for d in D])
    # each day weighs the same; within it the two classes weigh the same; NOISE frames are hard negatives
    w = np.zeros(len(y)); i = 0
    days = sorted({d['day'] for d in D})
    dayv = np.concatenate([[d['day']] * int(d['keep'].sum()) for d in D])
    for day in days:
        for cls in (0, 1):
            m = (dayv == day) & (y == cls)
            if m.any(): w[m] = 1.0 / m.sum()
    w *= np.where(nz, NOISE_W, 1.0)
    return X, y, w / w.mean()


def threshold_for(D, scores, target):
    u = np.concatenate([s[(d['y'][d['keep']] == 0) & ~d['noise'][d['keep']]] for d, s in zip(D, scores)])
    return float(np.quantile(u, 1 - target))


def unl_rate(D):
    on = np.concatenate([d['base'][d['keep']][(d['y'][d['keep']] == 0) & ~d['noise'][d['keep']]] for d in D])
    return float(on.mean())


def flat(node, out):
    """Tuple tree from a9.grow -> flat arrays (feature -1 marks a leaf), preorder."""
    i = len(out['feature'])
    for k in out: out[k].append(0)
    if node[0] == 'leaf':
        out['feature'][i], out['threshold'][i], out['left'][i], out['right'][i], out['value'][i] = -1, 0.0, -1, -1, round(float(node[1]), 4)
        return i
    _, f, c, L, R, p, _n = node
    out['feature'][i], out['threshold'][i], out['value'][i] = int(f), float(c), round(float(p), 4)
    out['left'][i] = flat(L, out); out['right'][i] = flat(R, out)
    return i


def cfloat(v):
    s = f'{v:.9g}'
    return (s if any(c in s for c in '.e') else s + '.0') + 'f'


def c_header(model):
    n = [len(t['feature']) for t in model['trees']]
    off = np.concatenate(([0], np.cumsum(n)))[:-1]
    cat = lambda k: [v for t in model['trees'] for v in t[k]]
    fmt = lambda vs, f: ',\n  '.join(', '.join(f(v) for v in vs[i:i + 12]) for i in range(0, len(vs), 12))
    feats = '\n'.join(f' *   {i}: {n_}' for i, n_ in enumerate(model['features']))
    return f"""// Generated by analysis/ad3_label_review/train_forest.py - do not edit.
// {model['name']} ({model['status']}): {len(n)} trees, depth <= {model['max_depth']}, {sum(n)} nodes.
// Model of {model['name']} ({lff.MODEL_FILE.name}); used through lowfreq_forest_core.h, which the
// firmware does not call yet (reference only). Inputs (causal, 250 ms windows of
// CH1/CH2 1-40 Hz RMS; x = ln(rms / trailing 30 s 20th percentile)):
/*
{feats}
 */
#pragma once
#include <stdint.h>

#define LFF_N_TREES {len(n)}
#define LFF_N_FEATURES {len(model['features'])}
#define LFF_THRESHOLD {model['threshold']:.4f}f

static const uint16_t lff_root[LFF_N_TREES] = {{{', '.join(str(int(o)) for o in off)}}};
static const int8_t lff_feature[{sum(n)}] = {{
  {fmt(cat('feature'), str)}}};
static const float lff_threshold[{sum(n)}] = {{
  {fmt(cat('threshold'), cfloat)}}};
// children are tree-local indices
static const int16_t lff_left[{sum(n)}] = {{
  {fmt(cat('left'), str)}}};
static const int16_t lff_right[{sum(n)}] = {{
  {fmt(cat('right'), str)}}};
static const float lff_value[{sum(n)}] = {{
  {fmt(cat('value'), lambda v: f'{v:.4f}f')}}};

static inline float lff_predict(const float x[LFF_N_FEATURES]) {{
  float sum = 0.0f;
  for (int t = 0; t < LFF_N_TREES; ++t) {{
    const uint16_t base = lff_root[t];
    int16_t i = 0;
    while (lff_feature[base + i] >= 0)
      i = x[lff_feature[base + i]] <= lff_threshold[base + i] ? lff_left[base + i] : lff_right[base + i];
    sum += lff_value[base + i];
  }}
  return sum / LFF_N_TREES;
}}
"""


def main():
    # only runs a person has labelled (any LARVA/DIG/NOISE mark); unreviewed runs are not negatives
    D = [run_data(r) for r in runs() if labels(r['run'])[0]]
    days = sorted({d['day'] for d in D})
    print('frames usable', sum(int(d['keep'].sum()) for d in D), 'runs', len(D), 'days', days)
    for held in days:
        tr = [d for d in D if d['day'] != held]; te = [d for d in D if d['day'] == held]
        f = Forest(**KW).fit(*xyw(tr)); sc = [f.predict(d['X'][d['keep']]) for d in te]
        yy = np.concatenate([d['y'][d['keep']] for d in te]); bs = [d['base'][d['keep']] for d in te]
        print(f"\nleave-one-day-out, test {held}:")
        print(f"  threshold 3.0  AP {ap(np.concatenate(bs) + 1e-9 * np.random.default_rng(0).random(len(yy)), yy):.2f}  {evaluate(te, bs, .5)[0]}")
        print(f"  forest         AP {ap(np.concatenate(sc), yy):.2f}  {evaluate(te, sc, threshold_for(te, sc, unl_rate(te)))[0]}")
    sc = []
    for i, d in enumerate(D):
        f = Forest(**KW).fit(*xyw([e for j, e in enumerate(D) if j != i])); sc.append(f.predict(d['X'][d['keep']]))
    print(f"\nleave-one-run-out (all {len(D)} runs):")
    print(f"  threshold 3.0  {evaluate(D, [d['base'][d['keep']] for d in D], .5)[0]}")
    print(f"  forest         {evaluate(D, sc, threshold_for(D, sc, unl_rate(D)))[0]}")
    if '--report' in sys.argv:
        return
    f = Forest(**KW).fit(*xyw(D))
    full = [f.predict(d['X'][d['keep']]) for d in D]
    thr = round(threshold_for(D, full, unl_rate(D)), 4)   # same unlabelled-time rate as threshold 3.0 (in-sample)
    print(f"\nfinal (all runs, in-sample) threshold {thr}: {evaluate(D, full, thr)[0]}")
    trees = []
    for t in f.trees:
        out = dict(feature=[], threshold=[], left=[], right=[], value=[]); flat(t, out); trees.append(out)
    model = dict(schema=lff.SCHEMA, name='lowfreq_forest_v1', status='PROVISIONAL_20261120_24_RUNS_20261118_19',
                 features=lff.FEATURES, threshold=thr, max_depth=KW['max_depth'], params=KW,
                 training_runs=[d['run'] for d in D], label_positive=['LARVA', 'DIG'], noise_weight=NOISE_W,
                 note='Threshold: same unlabelled-time rate as lowfreq_activity ratio>=3.0 on the training runs. '
                      'Leave-one-day-out results are printed by train_forest.py --report.', trees=trees)
    lff.MODEL_DIR.mkdir(parents=True, exist_ok=True)
    lff.MODEL_FILE.write_text(json.dumps(model, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    lff.HEADER_FILE.write_text(c_header(model), encoding='utf-8')
    # the host inference (flat arrays) must agree with the training trees
    for d, s in zip(D, full):
        assert np.allclose(lff.predict(model, d['X'][d['keep']]), s, atol=1e-3)
    print('wrote', lff.MODEL_FILE, sum(len(t['feature']) for t in trees), 'nodes')


if __name__ == '__main__':
    main()
